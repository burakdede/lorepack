#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { registerCommands } from '../packages/cli/dist/commands/index.js';

const ROOT = join(import.meta.dirname, '..');
const OUTPUT = join(ROOT, 'docs', 'cli-reference.md');

const GLOBAL_OPTIONS = [
  ['-v, --version', 'print the CLI version'],
  ['--json', 'emit machine-readable output on stdout'],
  ['--verbose', 'include stage detail and debug diagnostics'],
  ['--no-color', 'disable colour'],
  ['--cwd <path>', 'run against a project in another directory'],
  ['-h, --help', 'display help for the command'],
];

const args = new Set(process.argv.slice(2));
const check = args.has('--check');

function usageFor(command) {
  const pieces = ['lore', command.name];
  for (const argument of command.arguments ?? []) {
    pieces.push(argument.required === false ? `[${argument.name}]` : `<${argument.name}>`);
  }
  return pieces.join(' ');
}

function table(rows) {
  if (rows.length === 0) return 'None.\n';
  return [
    '| Name | Description |',
    '|---|---|',
    ...rows.map(
      ([name, description]) => `| \`${escapePipes(name)}\` | ${escapePipes(description)} |`,
    ),
    '',
  ].join('\n');
}

function escapePipes(value) {
  return String(value).replaceAll('|', '\\|');
}

function defaultSuffix(value) {
  if (value === undefined) return '';
  return ` Default: \`${String(value)}\`.`;
}

const commands = registerCommands();
const lines = [
  '# CLI reference',
  '',
  '<!-- Generated by scripts/generate-cli-reference.mjs. Do not edit by hand. -->',
  '',
  'This page is generated from `packages/cli/src/commands/*` after `pnpm build`.',
  'Run `pnpm cli:docs` to update it, or `pnpm cli:docs:check` to verify it is current.',
  '',
  '## Global options',
  '',
  table(GLOBAL_OPTIONS),
];

for (const command of commands) {
  lines.push(`## \`lore ${command.name}\``, '');
  lines.push(command.description, '');
  lines.push('```text', usageFor(command), '```', '');
  lines.push('### Arguments', '');
  lines.push(
    table(
      (command.arguments ?? []).map((argument) => [
        `${argument.required === false ? '[' : '<'}${argument.name}${argument.required === false ? ']' : '>'}`,
        argument.description,
      ]),
    ),
  );
  lines.push('### Flags', '');
  lines.push(
    table(
      (command.flags ?? []).map((flag) => [
        flag.flags,
        `${flag.description}${defaultSuffix(flag.defaultValue)}`,
      ]),
    ),
  );
}

const generated = `${lines.join('\n').replaceAll(/\n{3,}/g, '\n\n')}\n`;

if (check) {
  const current = readFileSync(OUTPUT, 'utf8');
  if (current !== generated) {
    console.error('cli:docs:check: docs/cli-reference.md is stale');
    console.error('Run `pnpm cli:docs` after `pnpm build`.');
    process.exit(1);
  }
  console.log('cli:docs:check: docs/cli-reference.md is current');
} else {
  writeFileSync(OUTPUT, generated);
  console.log('cli:docs: wrote docs/cli-reference.md');
}
